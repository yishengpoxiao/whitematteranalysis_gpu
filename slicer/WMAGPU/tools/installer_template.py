"""Self-contained WMAGPU installer. Run inside the target 3D Slicer application."""
import base64
import io
import os
from pathlib import Path
import platform
import sys
import tempfile
import zipfile

PAYLOAD = '__WMA_PAYLOAD__'
SOURCE_REVISION = '__WMA_REVISION__'


def runtime_version(major, minor, python_version):
    if (int(major), int(minor)) < (5, 2):
        raise RuntimeError('WMAGPU requires Slicer 5.2 or newer.')
    if tuple(python_version[:2]) < (3, 8):
        raise RuntimeError('WMAGPU requires Slicer Python 3.8 or newer.')
    return '%d.%d' % (int(major), int(minor))


def make_archive(payload, output, version):
    """Build an OS-neutral scripted extension using the detected Slicer layout."""
    with zipfile.ZipFile(io.BytesIO(payload)) as source, zipfile.ZipFile(
            output, 'x', compression=zipfile.ZIP_DEFLATED) as target:
        for name in source.namelist():
            if name.startswith('Modules/'):
                destination = 'WMAGPU/lib/Slicer-%s/qt-scripted-modules/%s' % (
                    version, name[len('Modules/'):])
            elif name == 'metadata.s4ext':
                destination = 'WMAGPU/share/Slicer-%s/WMAGPU.s4ext' % version
            else:
                destination = 'WMAGPU/' + name
            target.writestr(destination, source.read(name))
        target.writestr('WMAGPU/BUILD.txt', 'Source revision: %s\nSlicer layout: %s\n' % (
            SOURCE_REVISION, version))
    return output


class Installer:
    def __init__(self):
        import qt
        import slicer
        from _WMAGPUInstallTorch import installation_arguments, python_slicer
        self.slicer = slicer
        self.version = runtime_version(slicer.app.majorVersion, slicer.app.minorVersion, sys.version_info)
        self.executable = python_slicer()
        self.workspace = tempfile.TemporaryDirectory(prefix='WMAGPU-installer-')
        self.root = Path(self.workspace.name)
        self.payload = base64.b64decode(PAYLOAD)
        with zipfile.ZipFile(io.BytesIO(self.payload)) as archive:
            # Paths are generated by the packager, never provided by user archives.
            archive.extractall(self.root)
        self.vendor = self.root / 'Modules/_vendor'
        self.dialog = qt.QDialog(slicer.util.mainWindow())
        self.dialog.windowTitle = 'Install WMA GPU'
        self.dialog.resize(680, 480)
        layout = qt.QVBoxLayout(self.dialog)
        label = qt.QLabel('Detected Slicer %s, Python %s, %s %s\n'
                         'Missing required dependencies will be installed automatically.\n'
                         'Existing NumPy and VTK versions are preserved.' % (
                             self.version, platform.python_version(), platform.system(), platform.machine()))
        layout.addWidget(label)
        self.gpu = qt.QCheckBox('Also check / install CUDA PyTorch (optional download)')
        try:
            installation_arguments()
        except RuntimeError as exc:
            self.gpu.enabled = False
            self.gpu.toolTip = str(exc)
            layout.addWidget(qt.QLabel('CPU mode: ' + str(exc)))
        self.gpu_supported = self.gpu.enabled
        layout.addWidget(self.gpu)
        self.button = qt.QPushButton('Install WMAGPU and required dependencies')
        self.button.connect('clicked(bool)', self.start)
        layout.addWidget(self.button)
        self.log = qt.QPlainTextEdit()
        self.log.readOnly = True
        self.log.setPlainText('Ready. Internet is needed only for missing packages.\n'
                              'Remove an installed older WMAGPU release before installing this one.')
        layout.addWidget(self.log)
        self.process = qt.QProcess(slicer.app)
        self.process.setProcessChannelMode(qt.QProcess.MergedChannels)
        self.process.connect('readyReadStandardOutput()', self.read_output)
        self.process.connect('finished(int,QProcess::ExitStatus)', self.finished)
        self.process.connect('errorOccurred(QProcess::ProcessError)', self.failed)
        environment = qt.QProcessEnvironment.systemEnvironment()
        environment.insert('WMA_PYTHON_SLICER', self.executable)
        environment.insert('MPLBACKEND', 'Agg')
        self.process.setProcessEnvironment(environment)
        self.phase = None
        self.gpu_installer = None

    def start(self, *args):
        try:
            if self.slicer.app.extensionsManagerModel().isExtensionInstalled('WMAGPU'):
                raise RuntimeError('WMAGPU is already installed. Remove it in Extensions Manager, restart Slicer, then rerun this installer.')
            self.button.enabled = self.gpu.enabled = False
            self.dialog.show()
            self.log.appendPlainText('Checking/installing dependencies in: ' + self.executable)
            self.launch('dependencies', ['--install'])
        except Exception as exc:
            self.complete(str(exc))

    def launch(self, phase, arguments):
        self.phase = phase
        self.process.start(self.executable, [str(self.vendor / 'WMADependencies.py')] + arguments)

    def read_output(self):
        text = self.process.readAllStandardOutput().data().decode('utf-8', errors='replace')
        if text:
            self.log.appendPlainText(text.rstrip())

    def finished(self, code, status):
        import qt
        self.read_output()
        if status != qt.QProcess.NormalExit or code:
            self.complete('Setup failed. Review the log, network access, writable Slicer Python, and available wheels. No extension was installed.')
        elif self.phase == 'dependencies':
            self.launch('verify', [])
        elif self.phase == 'verify':
            try:
                archive = self.root / ('WMAGPU-Slicer-%s.zip' % self.version)
                make_archive(self.payload, archive, self.version)
                manager = self.slicer.app.extensionsManagerModel()
                if not manager.installExtension(str(archive), False, True):
                    raise RuntimeError('Extensions Manager rejected the package. Review Slicer error log.')
                self.complete('WMAGPU installed successfully. Restart Slicer, then open Diffusion > WMA GPU.')
                if self.gpu.checked:
                    from _WMAGPUInstallTorch import TorchInstaller
                    import qt
                    # Reuse the same opt-in CUDA installer shown in workflow modules.
                    allow = qt.QCheckBox(self.dialog)
                    allow.checked = True
                    allow.hide()
                    button = qt.QPushButton(self.dialog)
                    button.hide()
                    self.gpu_installer = TorchInstaller(allow, button, self.log)
                    self.gpu_installer.start()
            except Exception as exc:
                self.complete(str(exc))

    def failed(self, error):
        import qt
        if error == qt.QProcess.FailedToStart:
            self.complete('Unable to start PythonSlicer: ' + self.process.errorString())

    def complete(self, message):
        self.phase = None
        self.log.appendPlainText(message)
        self.button.enabled = True
        self.gpu.enabled = self.gpu_supported


def show_installer():
    # Make pure installer helpers available before importing WMA or scientific deps.
    global WMAGPU_INSTALLER
    payload = base64.b64decode(PAYLOAD)
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        helper = archive.read('Modules/_vendor/WMATorchInstaller.py').decode('utf-8')
    import types
    module = types.ModuleType('_WMAGPUInstallTorch')
    exec(compile(helper, 'WMATorchInstaller.py', 'exec'), module.__dict__)
    sys.modules['_WMAGPUInstallTorch'] = module
    WMAGPU_INSTALLER = Installer()
    WMAGPU_INSTALLER.dialog.show()
    return WMAGPU_INSTALLER


if __name__ == '__main__':
    show_installer()
